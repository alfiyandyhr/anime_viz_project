// Optional real-browser verification. See tests/journey-verification.md for setup.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const base = process.env.ANIVIZ_BASE_URL || 'http://127.0.0.1:8765/';
const movies = 'tmdb:genre:Science Fiction', anime = 'anilist:genre:Sci-Fi';
const forward = 'movie-to-anime', reverse = 'anime-to-movies';
const field = page => page.locator('#recommendation-chart');
const dots = page => field(page).locator('.dust-node');
const remove = (page, key) => page.locator(`[data-remove-magnet="${key}"]`).click();
const choice = page => page.locator('#genre-magnet-choice');
const add = page => page.getByRole('button', { name: 'Add genre magnet' });
const selectGenre = async (page, key) => {
  await page.getByRole('radio', { name: 'Genre cohort' }).check();
  const select = choice(page);
  const border = await select.evaluate(el => getComputedStyle(el).borderColor);
  await select.focus();
  await select.selectOption(key);
  assert.deepEqual(await select.evaluate(el => {
    const style = getComputedStyle(el);
    return [style.borderColor, style.boxShadow];
  }), [border, 'none'], 'selecting a genre keeps the dropdown border neutral');
  await add(page).press('Enter');
};
const snapshot = page => page.evaluate(() => {
  const { magnetKeys, rankingSortKey, displayedKeys, ranking } = AnivizMain.snapshot();
  return { magnetKeys, rankingSortKey, displayedKeys, ranking: ranking.map(row => [row.key, row.scores, row.score]) };
});

(async () => {
  const browser = await chromium.launch({ headless: true,
    ...(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {}) });
  try {
    const errors = [];
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(base);
    await dots(page).first().waitFor();
    const inception = await snapshot(page);
    await selectGenre(page, movies);
    assert.match(await choice(page).locator('option:checked').innerText(), /Science Fiction movies \(214\)/);
    assert.match(await page.locator('#movie-magnets').innerText(), /Science Fiction movies\s+TMDB · 214 movies/);
    const combined = await snapshot(page);
    const inceptionTop = new Set(inception.ranking.slice(0, 30).map(([key]) => key));
    assert.equal(combined.ranking.slice(0, 30).filter(([key]) => !inceptionTop.has(key)).length, 6);
    await add(page).click();
    assert.match(await page.locator('#recommendation-status').innerText(), /already a magnet/);
    const actionMovies = 'tmdb:genre:Action';
    await selectGenre(page, actionMovies);
    const mixed = await snapshot(page);
    assert.deepEqual(mixed.magnetKeys, ['tmdb:27205', movies, actionMovies]);
    assert.ok(mixed.ranking.every(([, scores, mean]) => scores.length === 3 && mean === (scores[0] + scores[1] + scores[2]) / 3));
    await choice(page).selectOption('tmdb:genre:Horror');
    await add(page).click();
    assert.match(await page.locator('#recommendation-status').innerText(), /Three magnets are in place/);
    await page.getByRole('radio', { name: 'Title', exact: true }).check();
    await page.locator('#movie-suggestions').getByRole('button', { name: 'Interstellar' }).click();
    assert.match(await page.locator('#recommendation-status').innerText(), /Three magnets are in place/);
    assert.deepEqual(await snapshot(page), mixed);
    await remove(page, actionMovies);
    assert.deepEqual(await snapshot(page), combined);

    const label = 'Science Fiction movies';
    const firstDot = dots(page).first();
    await firstDot.focus();
    assert.match(await firstDot.getAttribute('aria-label'), new RegExp(label));
    assert.match(await page.locator('#tooltip .dust-tooltip-score').nth(1).innerText(), /^Science Fiction movies\s/);
    await firstDot.press('Enter');
    await dots(page).nth(1).press('Space');
    assert.match(await page.locator('#dust-focus .dust-detail-scores').innerText(), new RegExp(label));
    assert.match(await page.locator('#recommendation-detail').textContent(), new RegExp(label));
    assert.match(await page.locator('#dust-mirror .dust-node').first().getAttribute('aria-label'), new RegExp(label));
    const connection = page.locator(`[data-dust-connection-movie="${movies}"]`);
    await page.locator('[data-dust-chart="connections"]').scrollIntoViewIfNeeded();
    await connection.press('Enter');
    assert.match(await page.locator('[data-coverage="connections"]').innerText(), new RegExp(label));
    assert.match(await page.locator('.dust-connection-row').first().getAttribute('aria-label'), new RegExp(label));
    const sort = page.locator('[data-dust-ranking-sort]');
    await sort.selectOption(movies);
    assert.equal(await page.getByRole('columnheader', { name: `M2 · ${label}`, exact: true }).count(), 1);
    await page.locator('[data-dust-rank-id]').first().press('Enter');
    assert.match(await page.locator('#detail-drawer .dust-detail-scores').innerText(), new RegExp(label));
    await page.keyboard.press('Escape');
    assert.doesNotMatch(await page.locator('body').innerText(), /mean cosine to/i);
    await page.getByText('About / Data', { exact: true }).click();
    assert.ok(await page.getByText('Genre magnets use mean cosine similarity.', { exact: false }).isVisible());

    const anchor = field(page).getByRole('group', { name: /Science Fiction movies magnet/ });
    const core = anchor.locator('.magnet-core');
    await core.scrollIntoViewIfNeeded();
    const { x, y, width, height } = await core.boundingBox();
    const before = await anchor.getAttribute('transform');
    await page.mouse.move(x + width / 2, y + height / 2);
    await page.mouse.down();
    await page.mouse.move(x + width / 2 + 30, y + height / 2 + 22, { steps: 5 });
    await page.mouse.up();
    const dragged = await anchor.getAttribute('transform');
    assert.notEqual(dragged, before);
    await page.reload();
    await dots(page).first().waitFor();
    assert.deepEqual((await snapshot(page)).magnetKeys, combined.magnetKeys);
    assert.equal(await sort.inputValue(), movies);
    assert.equal(await anchor.getAttribute('transform'), dragged);
    await page.selectOption('#dust-direction', reverse);
    await remove(page, 'anilist:16498');
    await selectGenre(page, anime);
    assert.match(await page.locator('#movie-magnets').innerText(), /Sci-Fi anime\s+AniList · 165 anime/);
    assert.equal(await page.getByRole('columnheader', { name: 'M1 · Sci-Fi anime', exact: true }).count(), 1);
    const reverseCohort = await snapshot(page);
    assert.deepEqual(reverseCohort.magnetKeys, [anime]);
    assert.equal(reverseCohort.ranking.length, 1000);
    await page.locator('[data-field-options] summary').click();
    await page.locator('#genre-filter').selectOption('Science Fiction');
    const filtered = await snapshot(page);
    assert.ok(filtered.displayedKeys.length > 0 && filtered.displayedKeys.length < reverseCohort.displayedKeys.length);
    assert.deepEqual(filtered.ranking, reverseCohort.ranking);
    const actionAnime = 'anilist:genre:Action', romanceAnime = 'anilist:genre:Romance';
    await selectGenre(page, actionAnime);
    await selectGenre(page, romanceAnime);
    assert.equal(await field(page).locator('.dust-magnet').count(), 3);
    const allGenres = await snapshot(page);
    assert.deepEqual(allGenres.magnetKeys, [anime, actionAnime, romanceAnime]);
    assert.ok(allGenres.ranking.every(([, scores, mean]) => scores.length === 3 && mean === (scores[0] + scores[1] + scores[2]) / 3));
    await page.reload();
    await dots(page).first().waitFor();
    assert.deepEqual(await snapshot(page), allGenres);
    await page.selectOption('#dust-direction', forward);
    await remove(page, movies);
    assert.equal(await sort.inputValue(), 'average');
    assert.deepEqual(await snapshot(page), inception);
    await page.selectOption('#dust-direction', reverse);
    assert.deepEqual(await snapshot(page), allGenres);

    const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
    mobile.on('pageerror', error => errors.push(error.message));
    await mobile.goto(base);
    await mobile.selectOption('#dust-direction', reverse);
    await selectGenre(mobile, anime);
    await dots(mobile).first().waitFor();
    const mobileAnchor = field(mobile).getByRole('group', { name: /Sci-Fi anime magnet/ });
    const mobileCore = mobileAnchor.locator('.magnet-core');
    await mobileCore.scrollIntoViewIfNeeded();
    const mobileBox = await mobileCore.boundingBox();
    const center = { x: mobileBox.x + mobileBox.width / 2, y: mobileBox.y + mobileBox.height / 2 };
    const touch = await mobile.context().newCDPSession(mobile);
    const mobileBefore = await mobileAnchor.getAttribute('transform');
    await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [center] });
    await touch.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: center.x + 20, y: center.y + 18 }] });
    await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
    const mobileDragged = await mobileAnchor.getAttribute('transform');
    assert.notEqual(mobileDragged, mobileBefore);
    await mobileAnchor.press('ArrowDown');
    assert.notEqual(await mobileAnchor.getAttribute('transform'), mobileDragged);
    await dots(mobile).first().press('Enter');
    const mobileFocus = await mobile.locator('#dust-focus').innerText();
    assert.match(mobileFocus, /Sci-Fi anime/);
    assert.doesNotMatch(mobileFocus, /mean cosine to/i);
    assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth), 390);
    await mobile.reload();
    await dots(mobile).first().waitFor();
    assert.deepEqual((await snapshot(mobile)).magnetKeys, ['anilist:16498', anime]);
    await remove(mobile, anime);
    assert.deepEqual((await snapshot(mobile)).magnetKeys, ['anilist:16498']);
    assert.deepEqual(errors, []);
    console.log('Verified mixed and three-cohort fields, the shared slot limit, rankings and filters, drag, keyboard use, and desktop/mobile session restoration.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
